/**
 * Writes src/plugin/bundled-texts.ts: the skill and the playbook as string constants, so the
 * plugin's setup and doctor read them with no Node and no file in the vault. The build runs it
 * first; src/plugin/bundled-texts.test.ts fails when the module and the files differ.
 * Run it alone with: node build/bundled-texts.mjs
 */
import { readFile, writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

export const BUNDLED = [
  ['SKILL', 'skills/recursive-board/SKILL.md'],
  ['PLAYBOOK', 'docs/playbook.md'],
]

export async function bundledTextsModule() {
  const constants = await Promise.all(BUNDLED.map(async ([name, path]) =>
    `/** ${path}. */\nexport const ${name} = ${JSON.stringify(await readFile(join(root, path), 'utf8'))}\n`))
  return '// Generated by build/bundled-texts.mjs from the files it names. Do not edit.\n\n' + constants.join('\n')
}

export async function writeBundledTexts() {
  const path = join(root, 'src', 'plugin', 'bundled-texts.ts')
  const text = await bundledTextsModule()
  if (await readFile(path, 'utf8').catch(() => null) !== text) await writeFile(path, text)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await writeBundledTexts()
